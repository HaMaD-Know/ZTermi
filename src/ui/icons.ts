export type IconName = keyof typeof ICONS;

export function icon(name: IconName, size = 18, className = ''): SVGElement {
  return createElement(ICONS[name], {
    width: size,
    height: size,
    'stroke-width': 1.8,
    'aria-hidden': 'true',
    class: `icon ${className}`.trim(),
  });
}
